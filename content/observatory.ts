export function countRussianWords(text: string) {
  return text.match(/[\p{L}\p{M}]+(?:[-’][\p{L}\p{M}]+)*|\d+/gu)?.length ?? 0;
}

export function getReadingTime(article: ObservatoryArticle) {
  const text = [article.title, article.lead, article.body, article.cta].join(" ");
  return Math.max(1, Math.ceil(countRussianWords(text) / READING_WORDS_PER_MINUTE));
}

export function getReadingLabel(article: ObservatoryArticle) {
  const minutes = getReadingTime(article);
  const mod10 = minutes % 10;
  const mod100 = minutes % 100;
  const unit = mod10 === 1 && mod100 !== 11 ? "минута" : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "минуты" : "минут";

  return `${minutes} ${unit} чтения`;
}
